const LAND = "#d5e5c9";

const mix = (count, max) => {
  if (!count) return LAND;
  const t = Math.max(0.28, Math.min(1, count / max));
  const r = Math.round(213 + (22 - 213) * t);
  const g = Math.round(229 + (51 - 229) * t);
  const b = Math.round(201 + (0 - 201) * t);
  return `rgb(${r},${g},${b})`;
};

const xy = (lon, lat) => {
  const x = ((lon + 180) / 360) * 1000;
  const y = ((85 - lat) / 150) * 470 + 8;
  return `${x.toFixed(1)} ${y.toFixed(1)}`;
};

const ring = (pts) => pts.map((pt, index) => `${index ? "L" : "M"}${xy(pt[0], pt[1])}`).join("") + "Z";

const land = (pts) =>
  `<path fill="${LAND}" stroke="#f4f7f1" stroke-width="0.6" d="${Array.isArray(pts[0][0]) ? pts.map(ring).join("") : ring(pts)}"></path>`;

const country = (name, pts, counts, max) => {
  const d = Array.isArray(pts[0][0]) ? pts.map(ring).join("") : ring(pts);
  return `<path data-country="${name}" d="${d}" fill="${mix(counts[name] || 0, max)}" stroke="#f4f7f1" stroke-width="0.7"><title>${name}${counts[name] ? ` · ${counts[name]}` : ""}</title></path>`;
};

