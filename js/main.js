const header = document.querySelector("[data-header]");
const menuToggle = document.querySelector("[data-menu-toggle]");
const mobileNav = document.querySelector("[data-mobile-nav]");
const year = document.querySelector("[data-year]");
const collapseBtn = document.querySelector("[data-collapse-nav]");
const langButtons = document.querySelectorAll("[data-lang-toggle]");
const metaDescription = document.querySelector('meta[name="description"]');

let lang = localStorage.getItem("immba-lang") === "zh" ? "zh" : "en";

if (year) {
  year.textContent = String(new Date().getFullYear());
}

const dict = () => translations[lang];

const applyLang = () => {
  const d = dict();
  document.documentElement.lang = lang === "zh" ? "zh-TW" : "en";
  document.body.dataset.lang = lang;
  document.title = d["meta.title"];
  if (metaDescription) metaDescription.setAttribute("content", d["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const value = d[key];
    if (!value) return;
    if (node.children.length) return;
    node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node.getAttribute("data-i18n-attr").split(",").forEach((pair) => {
      const [attr, key] = pair.split(":").map((part) => part.trim());
      if (attr && key && d[key]) node.setAttribute(attr, d[key]);
    });
  });

  langButtons.forEach((btn) => {
    btn.textContent = d.langButton;
    btn.setAttribute("aria-label", d.langAria);
  });

  syncCollapseLabel();
};

const syncCollapseLabel = () => {
  if (!collapseBtn) return;
  const collapsed = document.body.classList.contains("nav-collapsed");
  collapseBtn.textContent = collapsed ? dict()["notice.expand"] : dict()["notice.collapse"];
  collapseBtn.setAttribute("aria-expanded", String(!collapsed));
};

applyLang();

const setScrolled = () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 8);
};

setScrolled();
window.addEventListener("scroll", setScrolled, { passive: true });

const closeMenu = () => {
  if (!menuToggle || !mobileNav) return;
  mobileNav.hidden = true;
  menuToggle.setAttribute("aria-expanded", "false");
};

menuToggle?.addEventListener("click", () => {
  const open = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!open));
  mobileNav.hidden = open;
});

mobileNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

collapseBtn?.addEventListener("click", () => {
  document.body.classList.toggle("nav-collapsed");
  closeMenu();
  syncCollapseLabel();
});

langButtons.forEach((btn) => {
  btn.addEventListener("click", () => {
    lang = lang === "en" ? "zh" : "en";
    localStorage.setItem("immba-lang", lang);
    applyLang();
  });
});

const accordion = document.querySelector("[data-accordion]");
accordion?.addEventListener(
  "toggle",
  (event) => {
    const opened = event.target;
    if (!(opened instanceof HTMLDetailsElement) || !opened.open) return;
    accordion.querySelectorAll("details").forEach((item) => {
      if (item !== opened) item.open = false;
    });
  },
  true
);

document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
  anchor.addEventListener("click", (event) => {
    const id = anchor.getAttribute("href");
    if (!id || id === "#") return;
    const target = document.querySelector(id);
    if (!target) return;
    event.preventDefault();
    const offset = header ? header.offsetHeight + 8 : 0;
    const top = target.getBoundingClientRect().top + window.scrollY - offset;
    window.scrollTo({ top, behavior: "smooth" });
  });
});
